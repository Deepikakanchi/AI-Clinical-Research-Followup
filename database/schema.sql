-- =====================================================================
-- AI-Powered Clinical Research & Patient Follow-up Management
-- database/schema.sql  (US-03)
--
-- Run:  psql -U postgres -d clinical_followup -f database/schema.sql
--
-- WARNING: drops and recreates all 9 tables, so ALL DATA IS DELETED.
-- Run seed.sql afterwards to load the synthetic demo data.
--
-- Design rule: source facts (visit_notes), the AI proposal (ai_summaries)
-- and the human decision (summary_reviews) live in separate tables and
-- are never overwritten, so they can always be compared.
-- =====================================================================

DROP TABLE IF EXISTS users           CASCADE;
DROP TABLE IF EXISTS audit_events    CASCADE;
DROP TABLE IF EXISTS summary_reviews CASCADE;
DROP TABLE IF EXISTS ai_summaries    CASCADE;
DROP TABLE IF EXISTS visit_notes     CASCADE;
DROP TABLE IF EXISTS visits          CASCADE;
DROP TABLE IF EXISTS participants    CASCADE;
DROP TABLE IF EXISTS staff_members   CASCADE;
DROP TABLE IF EXISTS studies         CASCADE;
DROP FUNCTION IF EXISTS prevent_row_change() CASCADE;

-- ---------------------------------------------------------------------
-- 1. studies: fictional research studies
-- ---------------------------------------------------------------------
CREATE TABLE studies (
    study_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_code  VARCHAR(30)  NOT NULL UNIQUE
                CHECK (study_code ~ '^STD-[A-Z0-9-]{3,20}$'),
    title       VARCHAR(150) NOT NULL CHECK (length(trim(title)) >= 5),
    study_type  VARCHAR(20)  NOT NULL CHECK (study_type IN ('OBSERVATIONAL', 'REGISTRY')),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 2. staff_members: fictional coordinators and reviewers
--    (the one table added to the brief's seven; needed for role checks)
-- ---------------------------------------------------------------------
CREATE TABLE staff_members (
    staff_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_code     VARCHAR(20)  NOT NULL UNIQUE
                   CHECK (staff_code ~ '^(COORD|REV)-[0-9]{2}$'),
    display_label  VARCHAR(60)  NOT NULL,
    role           VARCHAR(20)  NOT NULL CHECK (role IN ('COORDINATOR', 'REVIEWER')),
    active         BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ---------------------------------------------------------------------
-- 3. participants: pseudonymous codes only, never real identifiers
-- ---------------------------------------------------------------------
CREATE TABLE participants (
    participant_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    study_id            INTEGER     NOT NULL REFERENCES studies(study_id) ON DELETE RESTRICT,
    participant_code    VARCHAR(10) NOT NULL CHECK (participant_code ~ '^P-[0-9]{4}$'),
    consent_status      VARCHAR(10) NOT NULL CHECK (consent_status IN ('ACTIVE', 'WITHDRAWN')),
    -- Ownership: the coordinator who manages and the reviewer assigned to this participant
    coordinator_code    VARCHAR(20) NOT NULL REFERENCES staff_members(staff_code),
    reviewer_code       VARCHAR(20) NOT NULL REFERENCES staff_members(staff_code),
    consent_updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    enrolled_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_participant_code_per_study UNIQUE (study_id, participant_code)
);

-- ---------------------------------------------------------------------
-- 4. visits: scheduled follow-ups
--    Due and Overdue are DERIVED in SQL, never stored.
-- ---------------------------------------------------------------------
CREATE TABLE visits (
    visit_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id    INTEGER     NOT NULL REFERENCES participants(participant_id) ON DELETE RESTRICT,
    scheduled_for     TIMESTAMPTZ NOT NULL,
    visit_type        VARCHAR(20) NOT NULL CHECK (visit_type IN ('BASELINE', 'FOLLOW_UP', 'CLOSE_OUT')),
    status            VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
                      CHECK (status IN ('SCHEDULED', 'COMPLETED', 'MISSED', 'CANCELLED')),
    coordinator_code  VARCHAR(20) NOT NULL REFERENCES staff_members(staff_code),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- No double-booking among SCHEDULED visits (cancelled/closed visits don't block a slot)
CREATE UNIQUE INDEX uq_visit_participant_time ON visits (participant_id, scheduled_for)
    WHERE status = 'SCHEDULED';
CREATE UNIQUE INDEX uq_visit_coordinator_time ON visits (coordinator_code, scheduled_for)
    WHERE status = 'SCHEDULED';

-- ---------------------------------------------------------------------
-- 5. visit_notes: source facts, append-only
-- ---------------------------------------------------------------------
CREATE TABLE visit_notes (
    note_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id           INTEGER     NOT NULL REFERENCES visits(visit_id) ON DELETE RESTRICT,
    observation_text   TEXT        NOT NULL
                       CHECK (length(trim(observation_text)) BETWEEN 20 AND 4000),
    follow_up_actions  JSONB       NOT NULL DEFAULT '[]'::jsonb
                       CHECK (jsonb_typeof(follow_up_actions) = 'array'
                              AND jsonb_array_length(follow_up_actions) <= 10),
    author_code        VARCHAR(20) NOT NULL REFERENCES staff_members(staff_code),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 6. ai_summaries: the model's proposal, never updated
--    SUCCEEDED rows must have a draft; FAILED rows must not.
-- ---------------------------------------------------------------------
CREATE TABLE ai_summaries (
    summary_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id           INTEGER     NOT NULL REFERENCES visits(visit_id) ON DELETE RESTRICT,
    generated_draft    JSONB,
    model_id           VARCHAR(80) NOT NULL,
    deployment_name    VARCHAR(80) NOT NULL,
    generation_status  VARCHAR(10) NOT NULL CHECK (generation_status IN ('SUCCEEDED', 'FAILED')),
    latency_ms         INTEGER     CHECK (latency_ms >= 0),
    error_code         VARCHAR(40),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_draft_matches_status CHECK (
        (generation_status = 'SUCCEEDED' AND generated_draft IS NOT NULL AND error_code IS NULL)
     OR (generation_status = 'FAILED'    AND generated_draft IS NULL     AND error_code IS NOT NULL)
    ),
    CONSTRAINT ck_draft_is_draft CHECK (
        generated_draft IS NULL OR generated_draft->>'review_status' = 'DRAFT'
    )
);

-- ---------------------------------------------------------------------
-- 7. summary_reviews: the reviewer's decision, one per draft
-- ---------------------------------------------------------------------
CREATE TABLE summary_reviews (
    review_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    summary_id        INTEGER     NOT NULL UNIQUE REFERENCES ai_summaries(summary_id) ON DELETE RESTRICT,
    final_text        TEXT,
    decision          VARCHAR(10) NOT NULL CHECK (decision IN ('APPROVED', 'REJECTED')),
    reviewer_code     VARCHAR(20) NOT NULL REFERENCES staff_members(staff_code),
    reviewer_comment  VARCHAR(1000),
    follow_up_flag    BOOLEAN     NOT NULL DEFAULT FALSE,
    reviewed_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_approved_has_text CHECK (
        decision <> 'APPROVED' OR (final_text IS NOT NULL AND length(trim(final_text)) BETWEEN 20 AND 4000)
    ),
    CONSTRAINT ck_rejected_has_comment CHECK (
        decision <> 'REJECTED' OR (reviewer_comment IS NOT NULL AND length(trim(reviewer_comment)) > 0)
    )
);

-- ---------------------------------------------------------------------
-- 8. audit_events: who did what and when, append-only
--    old_value / new_value hold status or code values only, NEVER note text.
-- ---------------------------------------------------------------------
CREATE TABLE audit_events (
    event_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type  VARCHAR(20) NOT NULL
                 CHECK (entity_type IN ('study', 'participant', 'visit', 'note', 'summary', 'review')),
    entity_id    INTEGER     NOT NULL,
    action       VARCHAR(40) NOT NULL,
    actor_code   VARCHAR(20) NOT NULL REFERENCES staff_members(staff_code),
    old_value    VARCHAR(60),
    new_value    VARCHAR(60),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ---------------------------------------------------------------------
-- 9. users: login accounts for staff (coordinators and reviewers)
--    Only what login needs: email, password hash and the link to staff_members.
--    The ROLE and NAME come from staff_members. Participants never log in.
-- ---------------------------------------------------------------------
CREATE TABLE users (
    user_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(120) NOT NULL UNIQUE
                   CHECK (email = lower(email) AND email ~ '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$'),
    password_hash  VARCHAR(100) NOT NULL,          -- bcrypt hash, never the password
    staff_code     VARCHAR(20)  NOT NULL UNIQUE REFERENCES staff_members(staff_code) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- Append-only guard: these rows can be inserted but never changed or
-- deleted. (This is a data-integrity rule, not business logic.)
-- ---------------------------------------------------------------------
CREATE FUNCTION prevent_row_change() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% is append-only: % is not allowed', TG_TABLE_NAME, TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_visit_notes_append_only
    BEFORE UPDATE OR DELETE ON visit_notes  FOR EACH ROW EXECUTE FUNCTION prevent_row_change();
CREATE TRIGGER trg_ai_summaries_append_only
    BEFORE UPDATE OR DELETE ON ai_summaries FOR EACH ROW EXECUTE FUNCTION prevent_row_change();
CREATE TRIGGER trg_audit_events_append_only
    BEFORE UPDATE OR DELETE ON audit_events FOR EACH ROW EXECUTE FUNCTION prevent_row_change();

-- ---------------------------------------------------------------------
-- Indexes for the screens' filters and the three demo queries
-- ---------------------------------------------------------------------
CREATE INDEX idx_participants_study     ON participants (study_id);
CREATE INDEX idx_participants_coordinator ON participants (coordinator_code);
CREATE INDEX idx_participants_reviewer  ON participants (reviewer_code);
CREATE INDEX idx_visits_participant     ON visits (participant_id);
CREATE INDEX idx_visits_status_date     ON visits (status, scheduled_for);
CREATE INDEX idx_notes_visit            ON visit_notes (visit_id, created_at);
CREATE INDEX idx_summaries_visit        ON ai_summaries (visit_id, created_at);
CREATE INDEX idx_audit_entity           ON audit_events (entity_type, entity_id, created_at);
